"""Write core/src/main/java/dev/holdfast/core/rules/CombatTimings.java from the animation source, so the server's
execution table (S7-S9), pairing distances and walker attack timers cannot drift from the exported clips.

Kill ticks use the measured weapon entry (build/contact.json from measure.py) when there is one, else the authored
impact. Free swings (ordinary melee) take their commit and contact ("strike") ticks from the exported clips' timeline
events, the same files clients play, so the server resolves a swing when its visual contact happens.
Run after make_all.sh and measure.py."""
import json, math, os
import walker_anims as wa
import contact_geometry as geometry
import execution_contacts

HERE = os.path.dirname(__file__)
BUILD = os.path.join(HERE, "..", "build")
OUT = os.path.join(HERE, "..", "..", "..", "core", "src", "main", "java", "dev", "holdfast", "core", "rules", "CombatTimings.java")
pair = json.load(open(os.path.join(BUILD, "pairing.json")))
EXTRAS = os.path.join(HERE, "..", "export", "assets", "holdfast", "player_animation_extras")
SWING_CLIPS = ("swing_knife", "swing_knife_heavy", "swing_machete", "swing_machete_heavy", "swing_hatchet",
               "swing_hatchet_heavy", "swing_katana", "swing_katana_heavy", "swing_axe", "swing_axe_overhead",
               "swing_bat", "swing_bat_heavy", "bat_charged_miss", "swing_unarmed", "swing_unarmed_heavy")
contact = json.load(open(os.path.join(BUILD, "contact.json"))) if os.path.exists(os.path.join(BUILD, "contact.json")) else {}


def tick(s):
    return int(round(s * 20))


# (weapon classes, posture, player clip, attacker clip, EXECS key, distance px)
ROWS = []
for w, classes in (("knife", "KNIFE"), ("axe", "AXE"), ("machete", "MACHETE,HATCHET"), ("katana", "KATANA"),
                   ("bat_charged", "BAT,HAMMER"), ("pistol", "PISTOL")):
    e = wa.EXECS[w]
    ROWS.append((classes, "UPRIGHT", f"exec_{w}", f"react_{w}", w, float(e["dist"])))
for w, classes in (("knife", "KNIFE"), ("axe", "AXE"), ("machete", "MACHETE,HATCHET"), ("katana", "KATANA"),
                   ("bat", "BAT,HAMMER"), ("pistol", "PISTOL")):
    ROWS.append((classes, "CRAWLER", f"exec_{w}_ground", f"react_{w}_ground", f"{w}_ground", pair[f"{w}_ground_crawler"]["dist"]))
    ROWS.append((classes, "PRONE", f"exec_{w}_ground", f"react_{w}_ground_prone", f"{w}_ground", pair[f"{w}_ground_prone"]["dist"]))

L = ["// GENERATED by art/characters/source/gen_core_tables.py from walker_anims.EXECS, build/pairing.json and",
     "// build/contact.json. Do not edit by hand; regenerate after changing the clips.",
     "package dev.holdfast.core.rules;", "", "import java.util.List;", "",
     "public final class CombatTimings {", "    private CombatTimings() {}", "",
     "    /** One paired execution: who may start it, against what, and the server's own ticks (S8, S9). */",
     "    public record Exec(List<WeaponClass> weapons, Posture posture, String playerClip, String targetClip,",
     "                       int commitTick, int killTick, int releaseTick, int lengthTicks, double distPx) {}", "",
     "    public static final List<Exec> EXECS = List.of("]
rows = []
for classes, posture, pc, tc, key, dist in ROWS:
    e = wa.EXECS[key]
    measured = (contact.get(pc) or {}).get("first_in")
    kill = geometry.kill_tick(measured, e["impact"])
    release = tick(e.get("release", e["impact"]))
    weapons = ", ".join(f"WeaponClass.{c}" for c in classes.split(","))
    rows.append(f"        new Exec(List.of({weapons}), Posture.{posture}, \"{pc}\", \"{tc}\", {tick(e['commit'])}, {kill}, "
                f"{release}, {int(math.ceil(e['length'] * 20))}, {round(dist, 2)})")
L.append(",\n".join(rows))
L += ["    );", "",
      "    /** One free swing: the clip clients play, and the server's commit and contact ticks from its timeline. */",
      "    public record Swing(String clip, int commitTick, int contactTick, int lengthTicks) {}", "",
      "    public static final List<Swing> SWINGS = List.of("]
swings = []
for name in SWING_CLIPS:
    a = json.load(open(os.path.join(EXTRAS, name + ".extras.json")))["animations"][name]
    events = {v: float(k) for k, v in a.get("timeline", {}).items()}
    strike = events["strike"]
    swings.append(f"        new Swing(\"{name}\", {tick(events.get('commit', 0.0))}, {tick(strike)}, "
                  f"{int(math.ceil(a['animation_length'] * 20 - 1e-9))})")
L.append(",\n".join(swings))
L += ["    );", "",
      "    public static Swing swing(String clip) {",
      "        for (Swing s : SWINGS) if (s.clip().equals(clip)) return s;",
      "        throw new IllegalArgumentException(\"no swing timing for \" + clip);",
      "    }", "",
      "    /**",
      "     * Skull centre at each execution reaction's impact, walker-local px {x, z} (the walker faces -z), from",
      "     * placement.py. The server aligns the player so this skull lands where the player clip strikes.",
      "     */",
      "    public static final java.util.Map<String, double[]> EXEC_SKULL = java.util.Map.ofEntries("]
L.append(",\n".join(f"        java.util.Map.entry(\"{k}\", new double[]{{{v[0]}, {v[1]}}})"
                    for k, v in sorted(pair["exec_skull"].items())))
L += ["    );", "",
      "    /** Measured skull surface entry and incoming direction, walker-local px, for each execution reaction. */",
      "    public record ExecContact(double x, double y, double z, double dx, double dy, double dz,",
      "                              boolean hasExit, double exitX, double exitY, double exitZ) {}",
      "    public static final java.util.Map<String, ExecContact> EXEC_CONTACT = java.util.Map.ofEntries("]
contacts = execution_contacts.generate()
L.append(",\n".join(f'        java.util.Map.entry("{name}", new ExecContact(' +
                   ', '.join(str(v) for v in row['point'] + row['direction']) + ', ' +
                   ('true' if row['exit'] else 'false') + ', ' + ', '.join(str(v) for v in (row['exit'] or [0.,0.,0.])) + '))'
                   for name,row in sorted(contacts.items())))
L += ["    );", "",
      "    /** Walker lunge: the server's own hit moment after the lunge starts (S1). */",
      "    public static final int LUNGE_HIT_TICK = 11, CRAWLER_LUNGE_HIT_TICK = 10;",
      "    /** Reach of a lunge or ankle grab, blocks (S1, proposed). */",
      "    public static final double GRAB_REACH = 1.2;",
      f"    /** Pairing distances for grabs, px (S2). */",
      f"    public static final double GRAB_DIST_UPRIGHT = {float(wa.GRAB_DIST)}, GRAB_DIST_PRONE = {pair['ankle_prone']['dist']}, "
      f"GRAB_DIST_CRAWLER = {pair['ankle_crawler']['dist']};",
      "}"]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(L) + "\n")
print("wrote", os.path.relpath(OUT), f"({len(rows)} executions, {len(swings)} swings)")
