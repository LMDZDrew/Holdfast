"""Write docs/animation_catalog.md from the exported files (so the catalog can't drift from them)."""
import json, os, glob

HERE = os.path.dirname(__file__)
A = os.path.join(HERE, "..", "export", "assets", "holdfast")
DOC = os.path.join(HERE, "..", "..", "..", "docs", "animation_catalog.md")
RIG = os.path.join(HERE, "..", "preview", "rig")


def loop(v):
    return {True: "loop", False: "once", "hold_on_last_frame": "hold last frame"}.get(v, str(v))


def events(a):
    ev = [f"`{v}` {float(t):.2f}" for t, v in sorted(a.get("timeline", {}).items(), key=lambda kv: float(kv[0]))]
    return ", ".join(ev) or "—"


def sounds(a):
    s = [f"{float(t):.2f} `{v['effect'].split(':')[-1]}`" for t, v in sorted(a.get("sound_effects", {}).items(), key=lambda kv: float(kv[0]))]
    return ", ".join(s) or "—"


lines = ["# Animation catalog", "",
         "Generated by `art/characters/source/gen_catalog.py` from `art/characters/export/`. Do not edit by hand.",
         "Times are seconds from the start of the clip. Events and sounds are **presentation cues**; see",
         "`docs/animation.md` for which ones the server must validate independently.", ""]

for fname, title, prefix in [("walker.animation.json", "Upright walker (GeckoLib, `animations/walker.animation.json`)", "animation.holdfast.walker."),
                             ("walker_crawler.animation.json", "Lower-half crawler (GeckoLib, `animations/walker_crawler.animation.json`)", "animation.holdfast.crawler.")]:
    d = json.load(open(os.path.join(A, "animations", fname)))["animations"]
    lines += [f"## {title}", "", "| Clip | Length | Playback | Bones keyed | Events | Sounds |", "|---|---:|---|---|---|---|"]
    for k, a in d.items():
        n = k.replace(prefix, "")
        bones = sorted(a["bones"])
        b = "body layer" if n.startswith("body.") else "arms layer" if n.startswith("arms.") else "head layer" if n.startswith("head.") else f"all ({len(bones)})"
        lines.append(f"| `{k}` | {a['animation_length']:.2f} | {loop(a['loop'])} | {b} | {events(a)} | {sounds(a)} |")
    lines.append("")

lines += ["## Player (Player Animator, `player_animation/<clip>.json`; extras in `player_animation_extras/<clip>.extras.json`)", "",
          "| Clip | Length | Playback | Parts keyed | Held prop | Events (from extras) | Sounds (from extras) |", "|---|---:|---|---|---|---|---|"]
for f in sorted(glob.glob(os.path.join(A, "player_animation", "*.json"))):
    k = os.path.basename(f)[:-5]
    a = list(json.load(open(f))["animations"].values())[0]
    x = json.load(open(os.path.join(A, "player_animation_extras", f"{k}.extras.json")))
    xa = list(x["animations"].values())[0]
    meta = x.get("holdfast_meta", {})
    prop = meta.get("weapon") or "—"
    if meta.get("vanilla_pose"):
        prop += f" (inside vanilla `{meta['vanilla_pose']}` pose)"
    lines.append(f"| `{k}` | {a['animation_length']:.2f} | {loop(a['loop'])} | {', '.join(sorted(a['bones']))} | {prop} | {events(xa)} | {sounds(xa)} |")
lines.append("")

sp = json.load(open(os.path.join(RIG, "gait_speeds.json")))
mv = json.load(open(os.path.join(RIG, "player_move_speeds.json")))
pr = json.load(open(os.path.join(RIG, "pairing.json")))
lines += ["## Reference speeds at 1× playback", "",
          "Scale playback by actual horizontal speed ÷ this value so feet don't slide.", "",
          "| Clip | Blocks per second |", "|---|---:|"]
lines += [f"| walker `body.{k}` | {v:.2f} |" for k, v in sp.items() if v]
lines += [f"| player `{k}` | {v:.2f} |" for k, v in mv.items()]
lines += ["", "## Pairing distances", "", "Distance in pixels (1/16 block) from the survivor's feet to the attacker's origin, along the survivor's facing; the attacker faces the survivor.", "",
          "| Pair | Distance (px) |", "|---|---:|", "| Upright grab (`grab_*` + `grabbed_*`) | 18 |"]
lines += [f"| {k} | {v['dist']:.2f} |" for k, v in pr.items() if "dist" in v]
lines += [f"| Execution `{k}` | {v} |" for k, v in [("knife", 18), ("bat_quick", 28), ("bat_charged", 28), ("axe", 26), ("machete", 22)]]
lines.append("")
open(DOC, "w").write("\n".join(lines))
print("wrote", os.path.relpath(DOC))
