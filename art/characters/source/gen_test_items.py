"""TEST ONLY. Item models for the animation harness, built from the preview weapon bones in build_model.py and
placed in the hand frame pa_item.py derives, so a held test weapon in game sits where the preview draws it.
They check the clips' wrist keys against the geometry those keys were solved for. They are not Holdfast's
real weapon items, whose models and display transforms are still to be authored.

Writes into testmod/animtest/src/main/resources/assets/holdfast_animtest/."""
import json, os
from PIL import Image
import build_model as bm
import pa_item

HERE = os.path.dirname(__file__)
RES = os.path.join(HERE, "..", "..", "..", "testmod", "animtest", "src", "main", "resources", "assets", "holdfast_animtest")
MODID = "holdfast_animtest"

# 4x4 swatches of one 16x16 texture: name -> (u, v, colour)
SWATCH = {"steel": (0, 0, (196, 200, 210)), "edge": (4, 0, (236, 238, 242)), "wood": (8, 0, (128, 92, 56)),
          "grip": (12, 0, (52, 40, 32)), "bat": (0, 4, (186, 146, 96)), "alu": (4, 4, (150, 156, 166)),
          "rubber": (8, 4, (30, 30, 30))}
# item -> (preview bone, material per cube, hand part the geometry is authored in, display name)
ITEMS = {
    "test_knife": ("knife", ["grip", "steel"], "rightItem", "Test Knife (animation harness)"),
    "test_bat": ("bat", ["grip", "bat"], "rightItem", "Test Bat (animation harness)"),
    "test_axe": ("axe", ["wood", "steel"], "rightItem", "Test Axe (animation harness)"),
    "test_machete": ("machete", ["grip", "steel"], "rightItem", "Test Machete (animation harness)"),
    # the left crutch is the right one mirrored about its own fist, so one model serves both hands
    "test_crutch": ("crutchR", ["alu", "rubber"], "rightItem", "Test Crutch (animation harness)"),
}
IDENTITY = {"rotation": [0, 0, 0], "translation": [0, 0, 0], "scale": [1, 1, 1]}


def elements(bone_name, materials, part):
    bone = next(b for b in bm.SURVIVOR if b["name"] == bone_name)
    out = []
    for c, mat in zip(bone["cubes"], materials):
        o, s = c["origin"], c["size"]
        a = pa_item.model_point(part, o)
        b = pa_item.model_point(part, [o[i] + s[i] for i in range(3)])
        lo, hi = [round(float(min(x, y)), 4) for x, y in zip(a, b)], [round(float(max(x, y)), 4) for x, y in zip(a, b)]
        assert all(-16 <= v <= 32 for v in lo + hi), (bone_name, lo, hi)
        u, v, _ = SWATCH[mat]
        face = {"uv": [u, v, u + 4, v + 4], "texture": "#t"}
        out.append({"from": lo, "to": hi, "faces": {f: dict(face) for f in ("north", "east", "south", "west", "up", "down")}})
    return out


def main():
    mdir, tdir, ldir = (os.path.join(RES, d) for d in ("models/item", "textures/item", "lang"))
    for d in (mdir, tdir, ldir):
        os.makedirs(d, exist_ok=True)
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for u, v, col in SWATCH.values():
        for y in range(v, v + 4):
            for x in range(u, u + 4):
                img.putpixel((x, y), col + (255,))
    img.save(os.path.join(tdir, "test_weapons.png"))
    lang = {}
    for item, (bone, mats, part, name) in ITEMS.items():
        model = {
            "_comment": "GENERATED by art/characters/source/gen_test_items.py. Test only: preview weapon geometry in "
                        "Player Animator's hand frame, identity third-person transforms.",
            "textures": {"t": f"{MODID}:item/test_weapons", "particle": f"{MODID}:item/test_weapons"},
            "elements": elements(bone, mats, part),
            "display": {"thirdperson_righthand": IDENTITY, "thirdperson_lefthand": IDENTITY,
                        "firstperson_righthand": IDENTITY, "firstperson_lefthand": IDENTITY,
                        "gui": {"rotation": [30, 45, 0], "translation": [0, 0, 0], "scale": [0.45, 0.45, 0.45]},
                        "ground": {"rotation": [0, 0, 0], "translation": [0, 2, 0], "scale": [0.4, 0.4, 0.4]},
                        "fixed": {"rotation": [0, 0, 0], "translation": [0, 0, 0], "scale": [0.5, 0.5, 0.5]}},
        }
        with open(os.path.join(mdir, f"{item}.json"), "w") as f:
            json.dump(model, f, indent=2)
        lang[f"item.{MODID}.{item}"] = name
    lang[f"entity.{MODID}.test_walker"] = "Test Walker (animation harness)"
    with open(os.path.join(ldir, "en_us.json"), "w") as f:
        json.dump(lang, f, indent=2)
    print("wrote", len(ITEMS), "test item models")


if __name__ == "__main__":
    main()
