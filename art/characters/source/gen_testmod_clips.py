"""Write testmod/animtest/.../Clips.java from the exported files, so the test mod's command suggestions,
pair presets and expected lengths can't drift from the exports."""
import glob, json, os
import walker_anims as wa

HERE = os.path.dirname(__file__)
A = os.path.join(HERE, "..", "export", "assets", "holdfast")
RIG = os.path.join(HERE, "..", "preview", "rig")
OUT = os.path.join(HERE, "..", "..", "..", "testmod", "animtest", "src", "main", "java", "dev", "holdfast", "animtest", "Clips.java")


def q(s):
    return '"' + s + '"'


walker = json.load(open(os.path.join(A, "animations", "walker.animation.json")))["animations"]
crawler = json.load(open(os.path.join(A, "animations", "walker_crawler.animation.json")))["animations"]
wk = {k.replace("animation.holdfast.walker.", ""): v for k, v in walker.items()}
ck = {k.replace("animation.holdfast.crawler.", ""): v for k, v in crawler.items()}
player = {}
for f in sorted(glob.glob(os.path.join(A, "player_animation", "*.json"))):
    name, a = next(iter(json.load(open(f))["animations"].items()))
    player[name] = a
pair = json.load(open(os.path.join(RIG, "pairing.json")))
weapon = {}
for name in player:
    meta = json.load(open(os.path.join(A, "player_animation_extras", f"{name}.extras.json")))["holdfast_meta"]
    if meta.get("weapon"):
        weapon[name] = meta["weapon"]

# (preset, player clip, attacker rig, attacker clip, distance px). Distances: docs/animation_catalog.md.
P = []
for p, w in [("seize", "grab_seize"), ("struggle", "grab_hold"), ("bitten", "grab_bite"), ("bite_blocked", "grab_bite_blocked"), ("shove", "grab_shoved")]:
    P.append((f"grab_{p}", f"grabbed_{p}", "walker", w, 18.0))
for p, w in [("seize", "prone_ankle_grab"), ("struggle", "prone_ankle_hold"), ("bitten", "prone_ankle_bite"),
             ("bite_blocked", "prone_ankle_bite_blocked"), ("kick", "prone_ankle_kicked")]:
    P.append((f"ankle_prone_{p}", f"grabbed_ankle_{p}", "walker", w, pair["ankle_prone"]["dist"]))
for p, w in [("seize", "crawler_reach"), ("struggle", "crawler_ankle_hold"), ("bitten", "crawler_ankle_bite"),
             ("bite_blocked", "crawler_ankle_bite_blocked"), ("kick", "crawler_ankle_kicked")]:
    P.append((f"ankle_crawler_{p}", f"grabbed_ankle_{p}", "crawler", w, pair["ankle_crawler"]["dist"]))
for w, d in [("knife", 18), ("bat_quick", 28), ("bat_charged", 28), ("axe", 26), ("machete", 22), ("katana", 36)]:
    P.append((f"exec_{w}", f"exec_{w}", "walker", f"react_{w}", float(d)))
for w in ("knife", "axe", "machete", "katana", "bat"):
    P.append((f"exec_{w}_ground_crawler", f"exec_{w}_ground", "crawler", f"react_{w}_ground", pair[f"{w}_ground_crawler"]["dist"]))
    P.append((f"exec_{w}_ground_prone", f"exec_{w}_ground", "walker", f"react_{w}_ground_prone", pair[f"{w}_ground_prone"]["dist"]))
for _, pc, rig, wc, _ in P:
    assert pc in player, pc
    assert wc in (ck if rig == "crawler" else wk), (rig, wc)

L = ["// GENERATED by art/characters/source/gen_testmod_clips.py from art/characters/export. Do not edit by hand.",
     "package dev.holdfast.animtest;", "", "import java.util.List;", "import java.util.Map;", "", "public final class Clips {",
     "    private Clips() {}", ""]


def mp(name, d):
    L.append(f"    /** clip name -> animation_length in seconds */")
    L.append(f"    public static final Map<String, Double> {name} = Map.ofEntries(")
    L.append(",\n".join(f"        Map.entry({q(k)}, {float(v['animation_length'])!r})" for k, v in d.items()))
    L.append("    );")
    L.append("")


mp("WALKER", wk)
mp("CRAWLER", ck)
mp("PLAYER", player)
L.append("    /** Cosmetic harness shot timing, from the same authored table as core execution ticks. */")
L.append("    public static final Map<String, Integer> PISTOL_SHOT_TICKS = Map.of(")
L.append(f'        "exec_pistol", {round(wa.EXECS["pistol"]["impact"] * 20)}, "exec_pistol_ground", {round(wa.EXECS["pistol_ground"]["impact"] * 20)});')
speed = json.load(open(os.path.join(RIG, "player_move_speeds.json")))
L.append("    /** injury movement clip -> speed as a fraction of vanilla walking (4.317 blocks/s) its footsteps match */")
L.append("    public static final Map<String, Double> MOVE_SPEED = Map.ofEntries(")
L.append(",\n".join(f"        Map.entry({q(k)}, {round(v / 4.317, 3)!r})" for k, v in sorted(speed.items())))
L.append("    );")
L.append("")
L.append("    /** player clip -> held prop from its extras file (knife, bat, axe, machete, crutch) */")
L.append("    public static final Map<String, String> WEAPON = Map.ofEntries(")
L.append(",\n".join(f"        Map.entry({q(k)}, {q(v)})" for k, v in sorted(weapon.items())))
L.append("    );")
L.append("")
L.append("    public record Pair(String name, String playerClip, boolean crawler, String attackerClip, double distPx) {}")
L.append("")
L.append("    public static final List<Pair> PAIRS = List.of(")
L.append(",\n".join(f"        new Pair({q(n)}, {q(pc)}, {'true' if rig == 'crawler' else 'false'}, {q(wc)}, {d!r})" for n, pc, rig, wc, d in P))
L.append("    );")
L.append("}")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(L) + "\n")
print("wrote", os.path.relpath(OUT), f"({len(wk)} walker, {len(ck)} crawler, {len(player)} player, {len(P)} pairs)")
